<?php



#creciente

for ($i=1; $i<=20; $i++) {
    echo $i . "<br>";
}

#decreciente

for ($i=20; $i>=1; $i--) {
    echo $i . "<br>";
}

#tabla de multiplicar creciente

$numuero=7;

for($i=1; $i<=12; $i++){
    echo $numuero . " x " . $i . " = " . ($numuero*$i) . "<br>";
}

#tabla de multiplicar decreciente

for($i=12; $i>=1; $i--){
    echo $numuero . " x " . $i . " = " . ($numuero*$i) . "<br>";
}